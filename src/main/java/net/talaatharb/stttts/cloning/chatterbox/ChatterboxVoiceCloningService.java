/**
 * Zero-shot English voice cloning with Resemble AI's Chatterbox (MIT) running on ONNX Runtime.
 *
 * <p>The reference recording is encoded into conditioning embeddings, speech tokens are generated by the 0.5B
 * Llama backbone (4-bit quantized) with a KV cache, and the conditional decoder turns them into a 24 kHz waveform.
 */
@Singleton
public class ChatterboxVoiceCloningService implements VoiceCloningService {
    private static final Logger LOG = LoggerFactory.getLogger(ChatterboxVoiceCloningService.class);
    static final String REPO = "onnx-community/chatterbox-ONNX";
    public static final int SAMPLE_RATE = 24_000;
    static final double MAX_REFERENCE_SECONDS = 10;
    private static final float REPETITION_PENALTY = 1.2f;
    private static final int MAX_CHUNK_CHARACTERS = 250;
    /*
     * DirectML runs the whole decoder in very large dispatches; past ~260 speech tokens (reference + new speech) a
     * 4 GB laptop GPU exceeds the Windows GPU watchdog and the device is reset. In GPU mode the reference is shortened
     * and the text split into smaller parts so most parts stay under the limit; longer ones are decoded on the CPU.
     */
    static final String GPU_TOKEN_LIMIT_PROPERTY = "stttts.chatterbox.gpuTokenLimit";
    private static final int DEFAULT_GPU_TOKEN_LIMIT = 250;
    private static final double GPU_REFERENCE_SECONDS = 6;
    private static final int GPU_CHUNK_CHARACTERS = 70;
    private static final OrtSession.SessionOptions.OptLevel DECODER_LEVEL =
            OrtSession.SessionOptions.OptLevel.EXTENDED_OPT;
    private static final String[] MODELS = {"speech_encoder", "embed_tokens", "language_model_q4",
        "conditional_decoder"};

    private final HuggingFaceDownloader downloader;
    private final Path directory;
    private ChatterboxTokenizer tokenizer;
    private OrtSession speechEncoder;
    private OrtSession embedTokens;
    private OrtSession languageModel;
    private OrtSession decoder;
    private OrtSession gpuDecoder;

    @Inject
    public ChatterboxVoiceCloningService(ModelStore store, HuggingFaceDownloader downloader) {
        this.downloader = downloader;
        this.directory = store.directory("chatterbox");
    }

    @Override
    public String id() {
        return "chatterbox";
    }

    @Override
    public String displayName() {
        return "Chatterbox (English voice cloning)";
    }

    @Override
    public String description() {
        return "Resemble AI's 0.5B model (MIT) with emotion exaggeration control. ~1.5 GB download.";
    }

    @Override
    public List<Language> languages() {
        return List.of(new Language("en", "English"));
    }

    @Override
    public double recommendedReferenceSeconds() {
        return MAX_REFERENCE_SECONDS;
    }

    @Override
    public boolean supportsExaggeration() {
        return true;
    }

    private List<RemoteFile> files() {
        List<RemoteFile> files = new ArrayList<>();
        for (String model : MODELS) {
            for (String suffix : new String[] {".onnx", ".onnx_data"}) {
                files.add(new RemoteFile(REPO, "onnx/" + model + suffix, directory.resolve(model + suffix)));
            }
        }
        files.add(new RemoteFile(REPO, "tokenizer.json", directory.resolve("tokenizer.json")));
        files.add(new RemoteFile(REPO, "default_voice.wav", directory.resolve("default_voice.wav")));
        return files;
    }

    /** The sample voice shipped with the model, handy as a reference when the user has none. */
    public Path defaultVoice() {
        return directory.resolve("default_voice.wav");
    }

    /** Downloads only the small sample voice (useful as a reference for any cloning engine). */
    public Path ensureDefaultVoice(ProgressListener progress) throws IOException {
        downloader.ensure(List.of(new RemoteFile(REPO, "default_voice.wav", defaultVoice())), progress);
        return defaultVoice();
    }

    @Override
    public boolean isInstalled() {
        return HuggingFaceDownloader.allPresent(files());
    }

    @Override
    public void install(ProgressListener progress) throws IOException {
        downloader.ensure(files(), progress);
    }

    @Override
    public synchronized AudioClip cloneVoice(VoiceCloneRequest request, ProgressListener progress) {
        try {
            install(progress.slice(0, 0.3));
            progress.update("Loading Chatterbox (this can take a while)...", -1);
            long started = System.nanoTime();
            load();
            LOG.info("Chatterbox models ready in {} ms", (System.nanoTime() - started) / 1_000_000);
            float exaggeration = Math.max(0.25f, Math.min(2f, request.exaggeration()));
            boolean gpu = gpuDecoder != null;
            AudioClip reference = request.reference().atSampleRate(SAMPLE_RATE)
                    .truncate(gpu ? GPU_REFERENCE_SECONDS : MAX_REFERENCE_SECONDS);
            progress.update("Analyzing the reference voice...", -1);
            try (Conditioning conditioning = encodeReference(reference)) {
                List<String> chunks = SupertonicText.chunk(ChatterboxTokenizer.normalize(request.text()),
                        gpu ? GPU_CHUNK_CHARACTERS : MAX_CHUNK_CHARACTERS);
                List<AudioClip> parts = new ArrayList<>();
                for (int i = 0; i < chunks.size(); i++) {
                    ProgressListener chunkProgress = progress.slice(0.3 + 0.7 * i / chunks.size(),
                            0.3 + 0.7 * (i + 1) / chunks.size());
                    String label = chunks.size() > 1 ? String.format(" (part %d of %d)", i + 1, chunks.size()) : "";
                    String text = ChatterboxTokenizer.normalize(chunks.get(i));
                    long generationStart = System.nanoTime();
                    long[] tokens = generate(text, exaggeration, conditioning, chunkProgress, label);
                    LOG.info("Generated {} speech tokens in {} ms", tokens.length,
                            (System.nanoTime() - generationStart) / 1_000_000);
                    chunkProgress.update("Decoding audio" + label, 0.95);
                    long decodeStart = System.nanoTime();
                    parts.add(decode(tokens, conditioning));
                    LOG.info("Decoded audio in {} ms", (System.nanoTime() - decodeStart) / 1_000_000);
                }
                progress.update("Done", 1);
                return AudioClip.concat(SAMPLE_RATE, 0.2, parts);
            }
        } catch (IOException | OrtException e) {
            throw new SpeechServiceException("Chatterbox voice cloning failed: " + e.getMessage(), e);
        }
    }

    private void load() throws IOException, OrtException {
        if (tokenizer == null) {
            tokenizer = ChatterboxTokenizer.load(directory.resolve("tokenizer.json"));
        }
        if (speechEncoder == null) {
            speechEncoder = Onnx.open(directory.resolve("speech_encoder.onnx"));
        }
        if (embedTokens == null) {
            embedTokens = Onnx.open(directory.resolve("embed_tokens.onnx"));
        }
        // DirectML can't run the language model's rotary GroupQueryAttention, so it always stays on the CPU.
        if (languageModel == null) {
            languageModel = Onnx.open(directory.resolve("language_model_q4.onnx"));
        }
        if (gpuDecoder == null && GpuRuntime.isEnabled()) {
            OrtSession session = Onnx.openAccelerated(directory.resolve("conditional_decoder.onnx"), DECODER_LEVEL);
            if (Onnx.isAccelerated(session)) {
                gpuDecoder = session;
            } else {
                decoder = session;
            }
        } else if (gpuDecoder != null && !GpuRuntime.isEnabled()) {
            gpuDecoder.close();
            gpuDecoder = null;
        }
        // The CPU decoder takes about a minute to initialize, so in GPU mode it is only opened for sequences the GPU
        // can't handle.
        if (decoder == null && gpuDecoder == null) {
            decoder = Onnx.open(directory.resolve("conditional_decoder.onnx"), DECODER_LEVEL);
        }
    }

    /** The decoder runs on the GPU (much faster) unless the sequence is long enough to trip the GPU watchdog. */
    private OrtSession decoderFor(int tokens) throws OrtException {
        if (gpuDecoder != null && tokens <= gpuDecoderTokenLimit()) {
            return gpuDecoder;
        }
        if (decoder == null) {
            decoder = Onnx.open(directory.resolve("conditional_decoder.onnx"), DECODER_LEVEL);
        }
        return decoder;
    }

    static int gpuDecoderTokenLimit() {
        return Integer.getInteger(GPU_TOKEN_LIMIT_PROPERTY, DEFAULT_GPU_TOKEN_LIMIT);
    }

    private Conditioning encodeReference(AudioClip reference) throws OrtException {
        try (OnnxTensor audio = OnnxTensor.createTensor(Onnx.env(), FloatBuffer.wrap(reference.samples()),
                new long[] {1, reference.samples().length})) {
            return new Conditioning(speechEncoder.run(Map.of("audio_values", audio)));
        }
    }

    /** Autoregressively generates speech tokens; the result already starts with the reference prompt tokens. */
    long[] generate(String text, float exaggeration, Conditioning conditioning, ProgressListener progress,
            String label) throws OrtException {
        OrtEnvironment env = Onnx.env();
        long[] inputIds = tokenizer.encodeForGeneration(text);
        int maxNewTokens = Math.min(1000, 60 + text.length() * 3);
        long[] positions = new long[inputIds.length];
        for (int i = 0; i < inputIds.length; i++) {
            positions[i] = inputIds[i] >= ChatterboxTokenizer.START_SPEECH ? 0 : i - 1;
        }
        List<Long> generated = new ArrayList<>();
        generated.add(ChatterboxTokenizer.START_SPEECH);
        Map<String, OnnxTensor> pastKeyValues = emptyCache(env);
        List<AutoCloseable> owned = new ArrayList<>(pastKeyValues.values());
        OrtSession.Result previous = null;
        int attentionLength = 0;
        try (OnnxTensor exaggerationTensor = OnnxTensor.createTensor(env, new float[] {exaggeration})) {
            for (int step = 0; step < maxNewTokens; step++) {
                progress.checkCancelled();
                progress.update(String.format("Generating speech%s: %d tokens", label, step),
                        0.9 * step / maxNewTokens);
                float[] embeds;
                long[] embedShape;
                try (OnnxTensor ids = OnnxTensor.createTensor(env, LongBuffer.wrap(inputIds),
                        new long[] {1, inputIds.length});
                        OnnxTensor pos = OnnxTensor.createTensor(env, LongBuffer.wrap(positions),
                                new long[] {1, positions.length});
                        OrtSession.Result embedded = embedTokens.run(
                                Map.of("input_ids", ids, "position_ids", pos, "exaggeration", exaggerationTensor))) {
                    OnnxTensor tensor = (OnnxTensor) embedded.get(0);
                    embedShape = tensor.getInfo().getShape();
                    embeds = toArray(tensor.getFloatBuffer());
                }
                if (step == 0) {
                    OnnxTensor condEmb = conditioning.tensor("cond_emb", 0);
                    long[] condShape = condEmb.getInfo().getShape();
                    float[] cond = toArray(condEmb.getFloatBuffer());
                    float[] joined = new float[cond.length + embeds.length];
                    System.arraycopy(cond, 0, joined, 0, cond.length);
                    System.arraycopy(embeds, 0, joined, cond.length, embeds.length);
                    embeds = joined;
                    embedShape = new long[] {1, condShape[1] + embedShape[1], embedShape[2]};
                }
                attentionLength += (int) embedShape[1];
                long[] mask = new long[attentionLength];
                java.util.Arrays.fill(mask, 1L);
                OrtSession.Result result;
                try (OnnxTensor embedTensor = OnnxTensor.createTensor(env, FloatBuffer.wrap(embeds), embedShape);
                        OnnxTensor maskTensor = OnnxTensor.createTensor(env, LongBuffer.wrap(mask),
                                new long[] {1, attentionLength})) {
                    Map<String, OnnxTensor> inputs = new HashMap<>(pastKeyValues);
                    inputs.put("inputs_embeds", embedTensor);
                    inputs.put("attention_mask", maskTensor);
                    result = languageModel.run(inputs);
                }
                if (previous != null) {
                    previous.close();
                }
                previous = result;
                Onnx.closeQuietly(owned.toArray(AutoCloseable[]::new));
                owned.clear();

                long next = nextToken((OnnxTensor) result.get(0), generated);
                generated.add(next);
                if (next == ChatterboxTokenizer.STOP_SPEECH) {
                    break;
                }
                pastKeyValues = presentToPast(result);
                inputIds = new long[] {next};
                positions = new long[] {step + 1};
            }
        } finally {
            if (previous != null) {
                previous.close();
            }
            Onnx.closeQuietly(owned.toArray(AutoCloseable[]::new));
        }
        long[] prompt = conditioning.longs("prompt_token", 1);
        int end = generated.get(generated.size() - 1) == ChatterboxTokenizer.STOP_SPEECH ? generated.size() - 1
                : generated.size();
        long[] tokens = new long[prompt.length + Math.max(0, end - 1)];
        System.arraycopy(prompt, 0, tokens, 0, prompt.length);
        for (int i = 1; i < end; i++) {
            tokens[prompt.length + i - 1] = generated.get(i);
        }
        return tokens;
    }

    private Map<String, OnnxTensor> emptyCache(OrtEnvironment env) throws OrtException {
        Map<String, OnnxTensor> cache = new LinkedHashMap<>();
        for (Map.Entry<String, NodeInfo> input : languageModel.getInputInfo().entrySet()) {
            if (input.getKey().startsWith("past_key_values")) {
                long[] shape = ((TensorInfo) input.getValue().getInfo()).getShape().clone();
                shape[0] = 1;
                shape[2] = 0;
                for (int i = 0; i < shape.length; i++) {
                    if (shape[i] < 0) {
                        shape[i] = i == 1 ? 16 : 64;
                    }
                }
                cache.put(input.getKey(), OnnxTensor.createTensor(env, FloatBuffer.allocate(0), shape));
            }
        }
        return cache;
    }

    private Map<String, OnnxTensor> presentToPast(OrtSession.Result result) {
        Map<String, OnnxTensor> cache = new LinkedHashMap<>();
        for (Map.Entry<String, OnnxValue> output : result) {
            String name = output.getKey();
            if (name.startsWith("present")) {
                cache.put(name.replaceFirst("^present", "past_key_values"), (OnnxTensor) output.getValue());
            }
        }
        return cache;
    }

    static long nextToken(OnnxTensor logitsTensor, List<Long> generated) {
        long[] shape = logitsTensor.getInfo().getShape();
        int vocab = (int) shape[shape.length - 1];
        FloatBuffer buffer = logitsTensor.getFloatBuffer();
        int offset = buffer.remaining() - vocab;
        float[] logits = new float[vocab];
        buffer.position(offset);
        buffer.get(logits);
        Set<Long> seen = new HashSet<>(generated);
        for (long token : seen) {
            if (token >= 0 && token < vocab) {
                float score = logits[(int) token];
                logits[(int) token] = score < 0 ? score * REPETITION_PENALTY : score / REPETITION_PENALTY;
            }
        }
        int best = 0;
        for (int i = 1; i < vocab; i++) {
            if (logits[i] > logits[best]) {
                best = i;
            }
        }
        return best;
    }

    private AudioClip decode(long[] tokens, Conditioning conditioning) throws OrtException {
        OrtSession session = decoderFor(tokens.length);
        LOG.info("Decoding {} speech tokens on the {}", tokens.length, session == gpuDecoder ? "GPU" : "CPU");
        try (OnnxTensor speechTokens = OnnxTensor.createTensor(Onnx.env(), LongBuffer.wrap(tokens),
                new long[] {1, tokens.length});
                OrtSession.Result result = session.run(Map.of("speech_tokens", speechTokens,
                        "speaker_embeddings", conditioning.tensor("ref_x_vector", 2),
                        "speaker_features", conditioning.tensor("prompt_feat", 3)))) {
            float[] wav = toArray(((OnnxTensor) result.get(0)).getFloatBuffer());
            return new AudioClip(wav, SAMPLE_RATE);
        }
    }

    private static float[] toArray(FloatBuffer buffer) {
        float[] values = new float[buffer.remaining()];
        buffer.get(values);
        return values;
    }

    @Override
    public synchronized void close() {
        Onnx.closeQuietly(speechEncoder, embedTokens, languageModel, decoder, gpuDecoder);
        speechEncoder = null;
        embedTokens = null;
        languageModel = null;
        decoder = null;
        gpuDecoder = null;
    }

    /** Outputs of the speech encoder for one reference recording. */
    static final class Conditioning implements AutoCloseable {
        private final OrtSession.Result result;

        Conditioning(OrtSession.Result result) {
            this.result = result;
        }

        OnnxTensor tensor(String name, int index) {
            return (OnnxTensor) result.get(name).orElseGet(() -> result.get(index));
        }

        long[] longs(String name, int index) {
            LongBuffer buffer = tensor(name, index).getLongBuffer();
            long[] values = new long[buffer.remaining()];
            buffer.get(values);
            return values;
        }

        @Override
        public void close() {
            result.close();
        }
    }
}
